import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'msedge',headless:true});
try {
  const page = await browser.newPage({viewport:{width:1120,height:720}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:1420', {waitUntil:'domcontentloaded'});
  async function createGroup(name,parent='') {
    await page.locator('#create-group').click();
    await page.locator('[name=name]').fill(name);
    await page.locator('[name=parent]').selectOption(parent);
    await page.locator('#editor button[type=submit]').click();
  }
  let initial=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  const names={'sys-settings':'Параметры Windows','sys-cmd':'Командная строка','sys-regedit':'Редактор реестра','sys-disks':'Управление дисками','sys-devices':'Диспетчер устройств','sys-control':'Панель управления'};
  for(const [id,name] of Object.entries(names))assert.equal(initial.apps.find(a=>a.id===id).name,name);
  await page.locator('nav [data-select="sys-prog"]').click();
  await page.locator('[data-edit="sys-cmd"]').click();
  assert.equal(await page.locator('[name=name]').getAttribute('maxlength'),'256');
  await page.locator('[name=name]').fill('Консоль');
  await page.locator('#editor button[type=submit]').click();
  await page.reload();
  initial=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(initial.apps.find(a=>a.id==='sys-cmd').name,'Консоль');
  assert.equal(initial.apps.find(a=>a.id==='sys-cmd').path,'cmd.exe');
  await createGroup('Работа');
  let data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  const root=data.groups.find(g=>g.name==='Работа').id;
  await createGroup('Средства',root);
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  const child=data.groups.find(g=>g.name==='Средства').id;
  await page.locator('#create-group').click();
  assert.equal(await page.locator('[name=parent] option[value="'+child+'"]').count(),1,'Nested groups can be parents');
  await page.locator('#editor .cancel').click();
  await createGroup('Глубже',child);
  await page.locator('#create-app').click();
  await page.locator('[name=name]').fill('Obsidian');
  await page.locator('[name=path]').fill('C:\\Apps\\Obsidian.exe');
  await page.locator('[name=parent]').selectOption(root);
  await page.locator('[name=position]').fill('1');
  await page.locator('#editor button[type=submit]').click();
  await page.locator(`nav [data-select="${root}"]`).click();
  assert.equal(await page.locator('.item-name').first().textContent(),'Obsidian');
  await page.locator('.item').first().locator('[data-direction="1"]').click();
  assert.equal(await page.locator('.item-name').first().textContent(),'Средства');
  await page.reload();
  await page.locator(`nav [data-select="${root}"]`).click();
  assert.equal(await page.locator('.item-name').first().textContent(),'Средства');
  await page.screenshot({path:'settings-preview.png'});
  await page.locator(`nav [data-select="${child}"]`).click();
  await page.locator('#edit-current').click();
  await page.locator('[name=name]').fill('Утилиты');
  await page.locator('#editor button[type=submit]').click();
  assert.equal(await page.locator('h1').textContent(),'Утилиты');
  await page.locator('[data-home]').click();
  await page.locator(`[data-delete="${root}"]`).click();
  await page.locator('#confirm [value=delete]').click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('spiderweb-preview')).groups.length===2);
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(data.groups.length,2); assert.equal(data.apps.length,7);
  for(let i=1;i<=4;i++) await createGroup(`Группа ${i}`);
  await page.locator('#create-group').click();
  await page.locator('[name=name]').fill('Восьмая');
  assert.equal(await page.locator('[name=position]').getAttribute('max'),'5');
  await page.locator('[name=position]').fill('6');
  assert.equal(await page.locator('[name=position]').evaluate(el=>el.checkValidity()),false);
  await page.locator('[name=position]').fill('5');
  await page.locator('#editor button[type=submit]').click();
  assert.match(await page.locator('.form-error').textContent(),/5 позиций заняты/);
  await page.locator('#editor .cancel').click();
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(data.groups.filter(g=>g.parentId===null).length,5);
  const fullRoot=data.groups.find(g=>g.name==='Группа 1').id;
  for(let i=1;i<=7;i++) await createGroup(`Подгр ${i}`,fullRoot);
  await page.locator('#create-app').click();
  await page.locator('[name=name]').fill('Лишнее');
  await page.locator('[name=path]').fill('C:\\Apps\\Extra.exe');
  await page.locator('[name=parent]').selectOption(fullRoot);
  await page.locator('#editor button[type=submit]').click();
  assert.match(await page.locator('.form-error').textContent(),/7 позиций заняты/);
  await page.locator('[name=parent]').selectOption(data.groups.find(g=>g.name==='Группа 2').id);
  await page.locator('#editor button[type=submit]').click();
  assert.equal(await page.locator('#editor').isVisible(),false);
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(data.apps.length,8);
  assert.ok([...data.groups,...data.apps].every(x=>x.position>=1&&x.position<=7));
  await page.locator('nav [data-select="sys-prog"]').click();
  assert.equal(await page.locator('#edit-current').count(),1);
  assert.equal(await page.locator('.fixed-label').count(),6);
  assert.equal(await page.locator('[data-delete="sys-prog"]').count(),0);
  assert.equal(await page.locator('[data-edit="sys-cmd"]').count(),1);
  await createGroup('Вторая','sys-prog');
  assert.match(await page.locator('.form-error').textContent(),/только одна/);
  await page.locator('#editor .cancel').click();
  await page.locator('[data-delete="sys-personal"]').click();
  await page.locator('#confirm [value=delete]').click();
  await createGroup('Личные','sys-prog');
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  const personal=data.groups.find(g=>g.parentId==='sys-prog');
  assert.equal(personal.position,7);
  await page.locator('nav [data-select="'+personal.id+'"]').click();
  await page.locator('#create-app').click();
  assert.equal(await page.locator('[name=parent] option[value="sys-prog"]').count(),0);
  await page.locator('[name=name]').fill('Редактор');
  await page.locator('[name=path]').fill('C:\\Apps\\Editor.exe');
  await page.locator('#editor button[type=submit]').click();
  await page.reload();
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(data.groups.filter(g=>g.id==='sys-prog').length,1);
  assert.equal(data.apps.filter(a=>a.groupId==='sys-prog').length,6);
  assert.ok(data.apps.some(a=>a.groupId===personal.id));
  await page.locator('#launcher-options').click();
  await page.locator('[name=mode]').selectOption('toggle');
  await page.locator('[name=trigger]').selectOption('keyboard');
  await page.locator('[name=key]').press('Alt+Space');
  await page.locator('#interaction-form button[type=submit]').click();
  await page.reload();
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.equal(data.launcher.mode,'toggle');
  assert.equal(data.launcher.trigger.key,32);
  assert.equal(data.launcher.trigger.modifiers,2);
  await page.locator('#launcher-options').click();
  assert.equal(await page.locator('[name=key]').inputValue(),'Alt + Space');
  await page.locator('[name=trigger]').selectOption('x1');
  await page.locator('#interaction-form button[type=submit]').click();
  data=await page.evaluate(()=>JSON.parse(localStorage.getItem('spiderweb-preview')));
  assert.deepEqual(data.launcher.trigger,{type:'mouse',button:'x1'});
  await page.locator('nav [data-select="sys-prog"]').click();
  await page.screenshot({path:'settings-preview.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: groups, nested levels, app assignment, positions, reorder, reload, edit, cascading deletion, no page errors.');
} finally { await browser.close(); }
